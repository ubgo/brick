// Package transpile turns one file's tree into one Go template source plus a
// table of component call sites.
//
// Why it exists: brick adds a calling convention to html/template, never a new
// language. Every component tag becomes an ordinary action that calls the
// engine (`__render`), every body becomes a hoisted `define`, and everything
// else is the author's bytes, copied verbatim. What html/template cannot
// express in text — which body belongs to which tag, which props are literal —
// lives in the Go-side Call table, so the generated text stays small and
// never has to encode data.
//
// The generated shapes (the runtime in package brick implements the __ funcs):
//
//	<Card title="Hi" :n="$i">body</Card>
//	  → {{ __render $ 3 . (__list $i) (__list ($i)) (__list) }}
//	    …
//	    {{ define "__brick_ab12_3" }}{{ $i := index .Vars 0 }}{{ $ := .Root }}{{ range __once .Dot }}body{{ end }}{{ end }}
//
// Invariants:
//   - author bytes outside actions are copied exactly; the transpiler adds no
//     bytes of output of its own, only actions that print nothing;
//   - a body sees the dot, `$` and `$variables` of the place it was written;
//   - every generated byte is covered by the source map, so errors from
//     html/template point at the author's file and line.
package transpile

import (
	"bytes"
	"fmt"
	"html"
	"regexp"
	"slices"
	"strconv"
	"strings"

	"github.com/ubgo/brick/internal/lex"
	"github.com/ubgo/brick/internal/tree"
)

// Runtime function names emitted into generated source. The runtime registers
// exactly these; every name starts with `__`, which authors cannot use (T5).
const (
	FnRender = "__render"
	FnList   = "__list"
	FnOnce   = "__once"
	FnCat    = "__cat"
	FnWrap   = "__wrap"
	// FnCallPrefix prefixes a rewritten script-namespace call (T7).
	FnCallPrefix = "__call_"
)

// ScopedFuncs are author-facing functions bound lexically to the file they
// are written in (T4): the transpiler rewrites `children` to `__children $`.
var ScopedFuncs = []string{"children", "node", "hasNode", "provide", "child", "attrs", "t", "nonce", "assets", "cacheTag", "dateFormat", "numberFormat", "image"}

// ScopedName is the runtime name of a lexically bound function.
func ScopedName(name string) string { return "__" + name }

// SpreadAttr passes a map's entries as props: `<Inner brick:spread=".Attrs" />`
// forwards a component's undeclared attributes. Its value is always an
// expression; an attribute written on the tag wins over the same key.
const SpreadAttr = "brick:spread"

// ReservedPrefix starts every engine-generated name.
const ReservedPrefix = "__"

// Input is one file to transpile.
type Input struct {
	File *tree.File
	// Name is the file's identity, used as the template name (T10).
	Name string
	// Hash is a short content hash; generated define names embed it (T5).
	Hash string
	// Line is the file line where the body starts (after frontmatter).
	Line int
	// Passthrough reports whether a component-looking element is emitted
	// verbatim as HTML (unknown-tag passthrough, S7, S8).
	Passthrough func(el *tree.Element) bool
	// Namespaces are the `use:` script namespaces whose calls are rewritten (T7).
	Namespaces map[string]bool
	// ScriptFuncs are the functions of the file's inline <brick:script>.
	ScriptFuncs map[string]bool
}

// CallName is the runtime name of a script function: `helpers.slugify` →
// `__call_helpers_slugify`, an inline `price` → `__call__price`. Each takes
// `$` first, so a script call reaches the render's context and limits (T8).
func CallName(namespace, fn string) string { return FnCallPrefix + namespace + "_" + fn }

// PropKind says how an attribute's value is produced.
type PropKind int

// Attribute kinds.
const (
	// Literal is `title="Hi"`: the string as written.
	Literal PropKind = iota
	// Bare is `open`: the boolean true.
	Bare
	// Expr is `:count="5"`: a Go template expression, evaluated at the call.
	Expr
	// Interp is `title="Hi {{ .N }}"`: a string built at the call.
	Interp
)

// Prop is one attribute on a call site.
type Prop struct {
	Name string
	Kind PropKind
	// Text is the literal value (Literal) or the source as written.
	Text string
	// Dyn is the index into the call's dynamic arguments (Expr, Interp).
	Dyn int
	Pos lex.Pos
}

// Node is a `<brick:prop>` block without `raw`: markup rendered lazily.
type Node struct {
	Name   string
	Define string
	Pos    lex.Pos
}

// RawProp is a `<brick:prop raw>` block: verbatim text.
type RawProp struct {
	Name string
	Text string
	Pos  lex.Pos
}

// Kid is one statically visible child for `.Children` (C7).
type Kid struct {
	// Call is the child's call site.
	Call int
	// Define renders the child alone (`{{ child $c }}`), executed with the
	// parent call's dot and variables.
	Define string
}

// Call is one component call site.
type Call struct {
	ID      int
	Name    string
	Pos     lex.Pos
	Element *tree.Element
	Props   []Prop
	// Vars are the `$variables` passed to the call, in argument order.
	Vars []string
	// Body is the define holding the children, "" when there are none.
	Body string
	// HasChildren is presence per C8: non-whitespace content was written.
	HasChildren bool
	Nodes       []Node
	RawProps    []RawProp
	Kids        []Kid
	// Raw holds a raw body (a raw component) and HasRaw says one was written.
	Raw    string
	HasRaw bool
	// action is the generated call action, reused by kid defines.
	action string
	// dyn is the generated code of each dynamic prop, by Prop.Dyn.
	dyn []string
	// refs are the variables the action uses (for kid eligibility).
	refs []string
}

// Local is a `<brick:component>` definition.
type Local struct {
	Name   string
	Define string
	Pos    lex.Pos
}

// Segment maps a range of generated source back to the author's file.
//
// Verbatim segments map offset-for-offset (the author's bytes were copied);
// fixed segments map every offset to Src (engine-generated text).
type Segment struct {
	Gen      int
	Len      int
	Src      lex.Pos
	Verbatim bool
}

// Output is the transpiled file.
type Output struct {
	Source string
	Calls  []*Call
	Locals []Local
	// Defines lists every generated define name, for diagnostics.
	Defines  []string
	Segments []Segment
	// Warnings are non-fatal findings (C7 children inside {{ if }}).
	Warnings []Warning
}

// Warning is a non-fatal finding with its position.
type Warning struct {
	Pos lex.Pos
	Msg string
	// Parent is the component call a children warning is about, so the
	// engine can drop the warning when that component never reads
	// .Children; nil for other warnings.
	Parent *tree.Element
}

// Error is a transpile error with its file-level position.
type Error struct {
	Pos lex.Pos
	Msg string
}

// Error renders line:col: message; the compiler adds the file and the
// body's line offset when it reports it.
func (e *Error) Error() string { return e.Pos.String() + ": " + e.Msg }

// Transpile generates the template source for one file.
func Transpile(in Input) (*Output, error) {
	t := &transpiler{in: in, out: &Output{}, byElement: map[*tree.Element]int{}}
	if t.in.Line < 1 {
		t.in.Line = 1
	}
	main := &writer{t: t}
	sc := newScope(nil)
	if err := t.nodes(main, in.File.Nodes, sc); err != nil {
		return nil, err
	}
	for _, l := range in.File.Locals {
		nameAttr, _ := l.Attr("name")
		if !lex.IsComponentName(nameAttr.Value) || strings.HasPrefix(nameAttr.Value, "brick:") || strings.HasPrefix(nameAttr.Value, "x-") {
			return nil, t.errAt(l.Pos, "<brick:component> needs name=\"…\" starting with an uppercase letter, got %q", nameAttr.Value)
		}
		for _, prev := range t.out.Locals {
			if prev.Name == nameAttr.Value {
				return nil, t.errAt(l.Pos, "<brick:component name=%q> is defined twice in this file (first at line %d)", nameAttr.Value, prev.Pos.Line)
			}
		}
		name := t.defineName()
		w := &writer{t: t}
		// A local component executes with its own scope as data, exactly like
		// a component file, so it gets no prologue and a fresh variable scope.
		if err := t.nodes(w, l.Children, newScope(nil)); err != nil {
			return nil, err
		}
		t.addDefine(name, w)
		t.out.Locals = append(t.out.Locals, Local{Name: nameAttr.Value, Define: name, Pos: t.filePos(l.Pos)})
	}
	// The main template first, then every hoisted define, each define's
	// segments shifted by where it lands.
	var src strings.Builder
	src.WriteString(main.buf.String())
	segs := slices.Clone(main.segs)
	for i, d := range t.defines {
		base := src.Len()
		src.WriteString(d)
		for _, s := range t.defineSegs[i] {
			s.Gen += base
			segs = append(segs, s)
		}
	}
	t.out.Source = src.String()
	t.out.Segments = segs
	return t.out, nil
}

type transpiler struct {
	in         Input
	out        *Output
	defines    []string
	defineSegs [][]Segment
	byElement  map[*tree.Element]int
	seq        int
}

func (t *transpiler) defineName() string {
	t.seq++
	name := fmt.Sprintf("__brick_%s_%d", t.in.Hash, t.seq)
	t.out.Defines = append(t.out.Defines, name)
	return name
}

// addDefine wraps a writer's content as `{{ define }}`, keeping its segments.
func (t *transpiler) addDefine(name string, w *writer) {
	head := `{{ define "` + name + `" }}`
	var segs []Segment
	for _, s := range w.segs {
		s.Gen += len(head)
		segs = append(segs, s)
	}
	t.defines = append(t.defines, head+w.buf.String()+"{{ end }}")
	t.defineSegs = append(t.defineSegs, segs)
}

// filePos converts a body-relative position to a file position.
func (t *transpiler) filePos(p lex.Pos) lex.Pos {
	p.Line += t.in.Line - 1
	return p
}

func (t *transpiler) errAt(p lex.Pos, format string, a ...any) *Error {
	return &Error{Pos: t.filePos(p), Msg: fmt.Sprintf(format, a...)}
}

// writer accumulates generated text with its source map.
type writer struct {
	t    *transpiler
	buf  strings.Builder
	segs []Segment
}

// copy writes author bytes that start at body position p.
func (w *writer) copy(b []byte, p lex.Pos) {
	if len(b) == 0 {
		return
	}
	w.segs = append(w.segs, Segment{Gen: w.buf.Len(), Len: len(b), Src: w.t.filePos(p), Verbatim: true})
	w.buf.Write(b)
}

// gen writes engine text attributed to body position p.
func (w *writer) gen(s string, p lex.Pos) {
	if s == "" {
		return
	}
	w.segs = append(w.segs, Segment{Gen: w.buf.Len(), Len: len(s), Src: w.t.filePos(p)})
	w.buf.WriteString(s)
}

// scope tracks the `$variables` Go's parser considers visible, frame by
// frame, mirroring text/template: a variable lives until the end of the
// control structure it was declared in.
type scope struct {
	frames [][]string
	// kinds parallels frames: the action that opened each frame.
	kinds []lex.ActKind
	// closers parallels frames: text emitted before the frame's {{ end }}.
	closers []string
}

func newScope(initial []string) *scope {
	return &scope{frames: [][]string{slices.Clone(initial)}, kinds: []lex.ActKind{lex.ActOther}, closers: []string{""}}
}

func (s *scope) visible() map[string]bool {
	m := map[string]bool{}
	for i := len(s.frames) - 1; i >= 0; i-- {
		for _, v := range s.frames[i] {
			m[v] = true
		}
		if s.kinds[i] == lex.ActDefine || s.kinds[i] == lex.ActBlock {
			break
		}
	}
	return m
}

func (s *scope) declare(vars []string) {
	s.frames[len(s.frames)-1] = append(s.frames[len(s.frames)-1], vars...)
}

func (s *scope) push(k lex.ActKind, vars []string, closer string) {
	s.frames = append(s.frames, slices.Clone(vars))
	s.kinds = append(s.kinds, k)
	s.closers = append(s.closers, closer)
}

// pop closes a frame and returns the text to emit before its `end`.
func (s *scope) pop() string {
	n := len(s.frames) - 1
	closer := s.closers[n]
	s.frames, s.kinds, s.closers = s.frames[:n], s.kinds[:n], s.closers[:n]
	return closer
}

// inLoopOrWith reports whether dot or variables differ from the body's start.
func (s *scope) inLoopOrWith() bool {
	for _, k := range s.kinds {
		if k == lex.ActRange || k == lex.ActWith {
			return true
		}
	}
	return false
}

func (s *scope) inIf() bool { return slices.Contains(s.kinds, lex.ActIf) }

func (t *transpiler) nodes(w *writer, nodes []tree.Node, sc *scope) error {
	for _, n := range nodes {
		switch n := n.(type) {
		case tree.Text:
			w.copy(n.Raw, n.Pos)
		case tree.Action:
			if err := t.action(w, n.Tok, sc); err != nil {
				return err
			}
		case *tree.Element:
			if err := t.element(w, n, sc); err != nil {
				return err
			}
		}
	}
	return nil
}

// action copies one author action, rewriting scoped functions, namespace
// calls and `template`/`define`/`block` so they keep brick's scope (T4, T7).
func (t *transpiler) action(w *writer, tok lex.Token, sc *scope) error {
	for _, id := range tok.Idents {
		if strings.HasPrefix(id.Name, ReservedPrefix) {
			return t.errAt(tok.Pos, "%q: names starting with __ are reserved for the engine", id.Name)
		}
	}
	switch tok.Act {
	case lex.ActEnd:
		closer := sc.pop()
		w.gen(closer, tok.Pos)
		w.copy(tok.Raw, tok.Pos)
		return nil
	case lex.ActDefine, lex.ActBlock:
		return t.defineOrBlock(w, tok, sc)
	case lex.ActOther:
		if word(tok.Raw) == "template" {
			return t.templateCall(w, tok, sc)
		}
	}
	t.rewriteInto(w, tok)
	switch {
	case tok.Act.Opens():
		sc.push(tok.Act, tok.Decls, "")
	default:
		sc.declare(tok.Decls)
	}
	return nil
}

// rewriteInto writes the action with its identifiers rewritten.
func (t *transpiler) rewriteInto(w *writer, tok lex.Token) {
	last := 0
	for _, id := range tok.Idents {
		repl, ok := t.replacement(id.Name)
		if !ok {
			continue
		}
		w.copy(tok.Raw[last:id.Start], advance(tok.Pos, tok.Raw[:last]))
		w.gen(repl, advance(tok.Pos, tok.Raw[:id.Start]))
		last = id.End
	}
	w.copy(tok.Raw[last:], advance(tok.Pos, tok.Raw[:last]))
}

// replacement is the rewritten form of an identifier, if it has one.
func (t *transpiler) replacement(name string) (string, bool) {
	if slices.Contains(ScopedFuncs, name) {
		return ScopedName(name) + " $", true
	}
	if ns, fn, ok := strings.Cut(name, "."); ok && t.in.Namespaces[ns] {
		return CallName(ns, fn) + " $", true
	}
	if t.in.ScriptFuncs[name] {
		return CallName("", name) + " $", true
	}
	return "", false
}

// rewriteCode rewrites a bare expression (from an attribute).
func (t *transpiler) rewriteCode(code string, p lex.Pos) (string, []string, error) {
	toks, err := lex.Scan([]byte("{{ "+code+" }}"), lex.Options{})
	if err != nil || len(toks) != 1 || toks[0].Kind != lex.Action {
		return "", nil, t.errAt(p, "invalid expression %q", code)
	}
	tok := toks[0]
	if tok.Act != lex.ActOther {
		return "", nil, t.errAt(p, "expression %q: only a value can go in an attribute, not a {{ }} block keyword", code)
	}
	if len(tok.Decls) > 0 {
		return "", nil, t.errAt(p, "expression %q: a variable cannot be declared inside an attribute", code)
	}
	var b strings.Builder
	last := 0
	for _, id := range tok.Idents {
		if strings.HasPrefix(id.Name, ReservedPrefix) {
			return "", nil, t.errAt(p, "%q: names starting with __ are reserved for the engine", id.Name)
		}
		repl, ok := t.replacement(id.Name)
		if !ok {
			continue
		}
		b.Write(tok.Raw[last:id.Start])
		b.WriteString(repl)
		last = id.End
	}
	b.Write(tok.Raw[last:])
	out := b.String()
	return strings.TrimSpace(out[2 : len(out)-2]), tok.Refs, nil
}

// templateCall rewrites `{{ template "x" P }}` to pass brick's scope along:
// `{{ template "x" (__wrap $ (P)) }}`. The define's prologue unwraps it.
func (t *transpiler) templateCall(w *writer, tok lex.Token, sc *scope) error {
	open, code, close := splitAction(tok.Raw)
	rest := strings.TrimSpace(strings.TrimPrefix(strings.TrimSpace(code), "template"))
	name, pipe, err := splitName(rest)
	if err != nil {
		return t.errAt(tok.Pos, "{{ template }}: %v", err)
	}
	if strings.HasPrefix(name, ReservedPrefix) {
		return t.errAt(tok.Pos, "template %q: names starting with __ are reserved for the engine", name)
	}
	arg := "nil"
	if strings.TrimSpace(pipe) != "" {
		rc, _, err := t.rewriteCode(pipe, tok.Pos)
		if err != nil {
			return err
		}
		arg = "(" + rc + ")"
	}
	w.gen(open+" template "+strconv.Quote(name)+" ("+FnWrap+" $ "+arg+") "+close, tok.Pos)
	sc.declare(tok.Decls)
	return nil
}

// defineOrBlock opens an author define/block with the unwrapping prologue.
func (t *transpiler) defineOrBlock(w *writer, tok lex.Token, sc *scope) error {
	open, code, close := splitAction(tok.Raw)
	kw := word(tok.Raw)
	rest := strings.TrimSpace(strings.TrimPrefix(strings.TrimSpace(code), kw))
	name, pipe, err := splitName(rest)
	if err != nil {
		return t.errAt(tok.Pos, "{{ %s }}: %v", kw, err)
	}
	if strings.HasPrefix(name, ReservedPrefix) {
		return t.errAt(tok.Pos, "%s %q: names starting with __ are reserved for the engine", kw, name)
	}
	head := open + " " + kw + " " + strconv.Quote(name) + " " + close
	if kw == "block" {
		arg := "nil"
		if strings.TrimSpace(pipe) != "" {
			rc, _, err := t.rewriteCode(pipe, tok.Pos)
			if err != nil {
				return err
			}
			arg = "(" + rc + ")"
		}
		head = open + " block " + strconv.Quote(name) + " (" + FnWrap + " $ " + arg + ") " + close
	}
	w.gen(head+prologue(nil), tok.Pos)
	// A define or block body sees none of the enclosing variables, as in Go;
	// its frame is a barrier for visible().
	sc.push(tok.Act, nil, epilogue)
	return nil
}

// prologue restores `$`, the caller's variables and the caller's dot at the
// top of a generated body (T2, T3). It prints nothing.
func prologue(vars []string) string {
	var b strings.Builder
	// By name, not position: a call's body, nodes and kids each declare only
	// the variables they use, from one map the call passes.
	for _, v := range vars {
		fmt.Fprintf(&b, "{{ $%s := index .Vars %q }}", v, v)
	}
	b.WriteString("{{ $ := .Root }}{{ range " + FnOnce + " .Dot }}")
	return b.String()
}

// epilogue closes the prologue's one-item range.
const epilogue = "{{ end }}"

func (t *transpiler) element(w *writer, el *tree.Element, sc *scope) error {
	if t.in.Passthrough != nil && t.in.Passthrough(el) {
		return t.passthrough(w, el, sc)
	}
	c, err := t.call(el, sc)
	if err != nil {
		return err
	}
	w.gen(c.action, el.Pos)
	return nil
}

// passthrough emits a component-looking tag verbatim (S7, S8).
func (t *transpiler) passthrough(w *writer, el *tree.Element, sc *scope) error {
	if len(el.Props) > 0 {
		return t.errAt(el.Pos, "<%s> is emitted as plain HTML, so it cannot take <brick:prop> blocks", el.Name)
	}
	for _, a := range el.Attrs {
		if strings.HasPrefix(a.Name, ":") {
			return t.errAt(a.Pos, "<%s> is emitted as plain HTML, so %s cannot be an expression; write %s=\"{{ … }}\"", el.Name, a.Name, strings.TrimPrefix(a.Name, ":"))
		}
	}
	if el.SelfClosing {
		// Browsers do not self-close unknown elements (S8).
		open := bytes.TrimRight(bytes.TrimSuffix(el.OpenRaw, []byte("/>")), " \t\r\n")
		w.copy(open, el.Pos)
		w.gen(">", el.Pos)
		w.gen("</"+el.Name+">", el.Pos)
		return nil
	}
	w.copy(el.OpenRaw, el.Pos)
	if err := t.nodes(w, el.Children, sc); err != nil {
		return err
	}
	w.gen(string(el.CloseRaw), el.Pos)
	return nil
}

// call builds a call site and its generated action.
func (t *transpiler) call(el *tree.Element, sc *scope) (*Call, error) {
	c := &Call{ID: len(t.out.Calls), Name: el.Name, Pos: t.filePos(el.Pos), Element: el}
	t.out.Calls = append(t.out.Calls, c)
	t.byElement[el] = c.ID
	visible := sc.visible()

	var dyn []string
	refs := map[string]bool{}
	seen := map[string]lex.Pos{}
	claim := func(name string, p lex.Pos) error {
		if prev, ok := seen[name]; ok {
			return t.errAt(p, "prop %q is given twice on <%s> (first at %s)", name, el.Name, t.filePos(prev))
		}
		seen[name] = p
		return nil
	}
	for _, a := range el.Attrs {
		name := strings.TrimPrefix(a.Name, ":")
		if name == "children" {
			return nil, t.errAt(a.Pos, "children is reserved: write the content between <%s> and </%s> instead", el.Name, el.Name)
		}
		if err := claim(name, a.Pos); err != nil {
			return nil, err
		}
		if strings.HasPrefix(a.Name, ":") && !a.HasValue {
			code, err := t.shorthand(el, a, visible)
			if err != nil {
				return nil, err
			}
			a.Value = code
		}
		p := Prop{Name: name, Pos: t.filePos(a.Pos), Text: a.Value}
		switch {
		case strings.HasPrefix(a.Name, ":") || a.Name == SpreadAttr:
			if strings.TrimSpace(a.Value) == "" {
				return nil, t.errAt(a.Pos, "%s has an empty expression", a.Name)
			}
			code, r, err := t.rewriteCode(a.Value, a.Pos)
			if err != nil {
				return nil, err
			}
			p.Kind, p.Dyn = Expr, len(dyn)
			dyn = append(dyn, "("+code+")")
			addRefs(refs, r)
		case !a.HasValue:
			p.Kind = Bare
		case strings.Contains(a.Value, "{{"):
			code, r, err := t.interp(a)
			if err != nil {
				return nil, err
			}
			p.Kind, p.Dyn = Interp, len(dyn)
			dyn = append(dyn, code)
			addRefs(refs, r)
		default:
			if strings.ContainsAny(a.Value, "<>\n") {
				return nil, t.errAt(a.Pos, "%s: angle brackets and newlines do not go in an attribute — use <brick:prop name=%q>…</brick:prop>", a.Name, name)
			}
			// A literal value is HTML attribute text, so its character
			// references mean what they mean in HTML: title="Tom &amp; Jerry"
			// is the text "Tom & Jerry", and a brick:click="f(&quot;x&quot;)"
			// passed on through {{ attrs }} is escaped once, not twice.
			p.Kind, p.Text = Literal, html.UnescapeString(a.Value)
		}
		c.Props = append(c.Props, p)
	}
	for _, bp := range el.Props {
		nameAttr, _ := bp.Attr(tree.AttrName)
		if err := claim(nameAttr.Value, bp.Pos); err != nil {
			return nil, err
		}
		if _, raw := bp.Attr(tree.AttrRaw); raw {
			c.RawProps = append(c.RawProps, RawProp{Name: nameAttr.Value, Text: rawText(bp.Children), Pos: t.filePos(bp.Pos)})
			continue
		}
		def, vars, err := t.body(bp.Children, visible)
		if err != nil {
			return nil, err
		}
		addRefs(refs, vars)
		c.Nodes = append(c.Nodes, Node{Name: nameAttr.Value, Define: def, Pos: t.filePos(bp.Pos)})
	}

	// Children: a raw body is text; anything else is a hoisted define.
	if len(el.Children) == 1 {
		if tx, ok := el.Children[0].(tree.Text); ok && tx.RawBody {
			c.Raw, c.HasRaw = string(tx.Raw), true
		}
	}
	if !c.HasRaw && present(el.Children) {
		c.HasChildren = true
		def, vars, err := t.body(el.Children, visible)
		if err != nil {
			return nil, err
		}
		c.Body = def
		addRefs(refs, vars)
	}

	// Variables the call passes: those its bodies need that exist here.
	for v := range refs {
		if visible[v] {
			c.Vars = append(c.Vars, v)
		}
	}
	slices.Sort(c.Vars)
	c.refs = sortedKeys(refs)
	if c.HasChildren {
		if err := t.kids(c, el.Children, visible); err != nil {
			return nil, err
		}
	}

	var kidArgs []string
	for _, k := range c.Kids {
		kc := t.out.Calls[k.Call]
		var ds []string
		for _, p := range kc.Props {
			if p.Kind == Expr || p.Kind == Interp {
				ds = append(ds, t.dynCode(kc, p))
			}
		}
		kidArgs = append(kidArgs, "("+FnList+listArgs(ds)+")")
	}
	var vars []string
	for _, v := range c.Vars {
		vars = append(vars, "$"+v)
	}
	c.action = fmt.Sprintf("{{ %s $ %d . (%s%s) (%s%s) (%s%s) }}", FnRender, c.ID, FnList, listArgs(vars), FnList, listArgs(dyn), FnList, listArgs(kidArgs))
	c.dyn = dyn
	return c, nil
}

// shorthandRE is the name a `:prop` shorthand may carry: a Go template
// variable name, since the shorthand passes `$name` and nothing else.
var shorthandRE = regexp.MustCompile(`^[A-Za-z_][A-Za-z0-9_]*$`)

// shorthand returns the expression of a valueless `:name` attribute:
// `<Card :post />` is `<Card :post="$post" />`.
// It names the template variable and only that: when no `$post` is in
// scope it is an error rather than a fallback to `.post`, so the same tag
// never means two things depending on where it sits.
func (t *transpiler) shorthand(el *tree.Element, a lex.Attr, visible map[string]bool) (string, error) {
	name := strings.TrimPrefix(a.Name, ":")
	switch {
	case name == "":
		return "", t.errAt(a.Pos, "<%s>: a bare %q names no prop; write :name=\"…\"", el.Name, a.Name)
	case !shorthandRE.MatchString(name):
		return "", t.errAt(a.Pos, "<%s>: %s with no value passes the variable of the same name, and %q is not a variable name; write %s=\"…\"", el.Name, a.Name, name, a.Name)
	case !visible[name]:
		return "", t.errAt(a.Pos, "<%s>: %s with no value passes $%s, but no $%s is declared here; declare it or write %s=\"…\"", el.Name, a.Name, name, name, a.Name)
	}
	return "$" + name, nil
}

// dynCode returns the generated code of a call's dynamic prop.
func (t *transpiler) dynCode(c *Call, p Prop) string { return c.dyn[p.Dyn] }

func listArgs(a []string) string {
	if len(a) == 0 {
		return ""
	}
	return " " + strings.Join(a, " ")
}

// body hoists nodes into a define with a prologue for the variables it uses,
// and returns the define name and those variables.
func (t *transpiler) body(nodes []tree.Node, visible map[string]bool) (string, []string, error) {
	var vars []string
	for v := range subtreeRefs(nodes) {
		if visible[v] {
			vars = append(vars, v)
		}
	}
	slices.Sort(vars)
	name := t.defineName()
	w := &writer{t: t}
	w.gen(prologue(vars), firstPos(nodes))
	sc := newScope(vars)
	if err := t.nodes(w, nodes, sc); err != nil {
		return "", nil, err
	}
	if len(sc.frames) != 1 {
		return "", nil, t.errAt(firstPos(nodes), "unbalanced {{ }} blocks in a component body")
	}
	w.gen(epilogue, firstPos(nodes))
	t.addDefine(name, w)
	return name, vars, nil
}

// kids collects the statically visible children of a call (C7) and gives
// each a define that renders it alone.
func (t *transpiler) kids(c *Call, nodes []tree.Node, visible map[string]bool) error {
	sc := newScope(nil)
	var walk func(ns []tree.Node) error
	walk = func(ns []tree.Node) error {
		for _, n := range ns {
			switch n := n.(type) {
			case tree.Action:
				switch {
				case n.Tok.Act == lex.ActEnd:
					sc.pop()
				case n.Tok.Act.Opens():
					sc.push(n.Tok.Act, n.Tok.Decls, "")
				default:
					sc.declare(n.Tok.Decls)
				}
			case *tree.Element:
				id, ok := t.byElement[n]
				if !ok {
					// A passthrough element is plain markup: look inside.
					if err := walk(n.Children); err != nil {
						return err
					}
					continue
				}
				if sc.inLoopOrWith() {
					continue
				}
				kc := t.out.Calls[id]
				usable := true
				for _, v := range kc.refs {
					if !visible[v] {
						usable = false
					}
				}
				if !usable {
					t.out.Warnings = append(t.out.Warnings, Warning{Pos: kc.Pos, Msg: fmt.Sprintf("<%s> uses a variable declared inside <%s>, so it is left out of .Children", kc.Name, c.Name)})
					continue
				}
				if sc.inIf() {
					t.out.Warnings = append(t.out.Warnings, Warning{Pos: kc.Pos, Msg: fmt.Sprintf("<%s> is inside {{ if }}, so it is listed in <%s>'s .Children even when the condition is false", kc.Name, c.Name), Parent: c.Element})
				}
				name := t.defineName()
				w := &writer{t: t}
				w.gen(prologue(c.Vars)+kc.action+epilogue, n.Pos)
				t.addDefine(name, w)
				c.Kids = append(c.Kids, Kid{Call: id, Define: name})
			}
		}
		return nil
	}
	return walk(nodes)
}

// interp turns `Hi {{ .N }}!` into `(__cat "Hi " (.N) "!")` (S2).
func (t *transpiler) interp(a lex.Attr) (string, []string, error) {
	toks, err := lex.Scan([]byte(a.Value), lex.Options{})
	if err != nil {
		return "", nil, t.errAt(a.Pos, "%s: %v", a.Name, err)
	}
	parts := []string{FnCat}
	var refs []string
	for _, tok := range toks {
		switch tok.Kind {
		case lex.Action:
			if tok.Act == lex.ActComment {
				continue
			}
			if tok.Act != lex.ActOther {
				return "", nil, t.errAt(a.Pos, "%s: a {{ }} block cannot go inside an attribute value; compute the value with an expression, e.g. :%s=\"…\"", a.Name, a.Name)
			}
			_, code, _ := splitAction(tok.Raw)
			rc, r, err := t.rewriteCode(code, a.Pos)
			if err != nil {
				return "", nil, err
			}
			parts = append(parts, "("+rc+")")
			refs = append(refs, r...)
		default:
			if strings.ContainsAny(string(tok.Raw), "<>\n") {
				return "", nil, t.errAt(a.Pos, "%s: angle brackets and newlines do not go in an attribute — use <brick:prop>", a.Name)
			}
			parts = append(parts, strconv.Quote(string(tok.Raw)))
		}
	}
	return "(" + strings.Join(parts, " ") + ")", refs, nil
}

// present reports C8 presence: any non-whitespace text, action or element.
func present(nodes []tree.Node) bool {
	for _, n := range nodes {
		switch n := n.(type) {
		case tree.Text:
			if len(bytes.TrimSpace(n.Raw)) > 0 {
				return true
			}
		case tree.Action:
			if n.Tok.Act != lex.ActComment {
				return true
			}
		case *tree.Element:
			return true
		}
	}
	return false
}

// rawText returns a raw block's text.
func rawText(nodes []tree.Node) string {
	var b strings.Builder
	for _, n := range nodes {
		if tx, ok := n.(tree.Text); ok {
			b.Write(tx.Raw)
		}
	}
	return b.String()
}

// subtreeRefs collects every `$variable` referenced under nodes, including
// in nested tags' attributes and blocks.
func subtreeRefs(nodes []tree.Node) map[string]bool {
	m := map[string]bool{}
	var walk func(ns []tree.Node)
	walk = func(ns []tree.Node) {
		for _, n := range ns {
			switch n := n.(type) {
			case tree.Action:
				addRefs(m, n.Tok.Refs)
			case *tree.Element:
				for _, a := range n.Attrs {
					addRefs(m, attrRefs(a))
				}
				for _, p := range n.Props {
					walk(p.Children)
				}
				walk(n.Children)
			}
		}
	}
	walk(nodes)
	return m
}

// attrRefs returns the variables an attribute value references.
func attrRefs(a lex.Attr) []string {
	src := a.Value
	if strings.HasPrefix(a.Name, ":") {
		if !a.HasValue {
			// The `:name` shorthand references $name (see shorthand).
			return []string{strings.TrimPrefix(a.Name, ":")}
		}
		src = "{{ " + src + " }}"
	}
	toks, err := lex.Scan([]byte(src), lex.Options{})
	if err != nil {
		return nil
	}
	var out []string
	for _, tok := range toks {
		out = append(out, tok.Refs...)
	}
	return out
}

func addRefs(m map[string]bool, refs []string) {
	for _, r := range refs {
		m[r] = true
	}
}

func sortedKeys(m map[string]bool) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	slices.Sort(out)
	return out
}

func firstPos(nodes []tree.Node) lex.Pos {
	for _, n := range nodes {
		switch n := n.(type) {
		case tree.Text:
			return n.Pos
		case tree.Action:
			return n.Tok.Pos
		case *tree.Element:
			return n.Pos
		}
	}
	return lex.Pos{Line: 1, Col: 1}
}

// advance returns the position after b, starting at p.
func advance(p lex.Pos, b []byte) lex.Pos {
	for _, c := range b {
		p.Offset++
		if c == '\n' {
			p.Line++
			p.Col = 1
		} else {
			p.Col++
		}
	}
	return p
}

// splitAction splits `{{- code -}}` into its delimiters and code.
func splitAction(raw []byte) (open, code, close string) {
	s := string(raw)
	open, close = "{{", "}}"
	s = s[2 : len(s)-2]
	if strings.HasPrefix(s, "- ") || strings.HasPrefix(s, "-\t") || strings.HasPrefix(s, "-\n") {
		open, s = "{{-", s[1:]
	}
	if strings.HasSuffix(s, " -") || strings.HasSuffix(s, "\t-") || strings.HasSuffix(s, "\n-") {
		close, s = "-}}", s[:len(s)-1]
	}
	return open, s, close
}

// word returns an action's first keyword.
func word(raw []byte) string {
	_, code, _ := splitAction(raw)
	code = strings.TrimSpace(code)
	i := 0
	for i < len(code) && (code[i] == '_' || (code[i] >= 'a' && code[i] <= 'z') || (code[i] >= 'A' && code[i] <= 'Z')) {
		i++
	}
	return code[:i]
}

// splitName splits `"name" pipeline` into the name and the pipeline.
func splitName(s string) (string, string, error) {
	if s == "" {
		return "", "", fmt.Errorf("missing a template name")
	}
	q := s[0]
	if q != '"' && q != '`' {
		return "", "", fmt.Errorf("the name must be a string literal")
	}
	end := -1
	for i := 1; i < len(s); i++ {
		if q == '"' && s[i] == '\\' {
			i++
			continue
		}
		if s[i] == q {
			end = i
			break
		}
	}
	if end < 0 {
		return "", "", fmt.Errorf("unterminated name")
	}
	name, err := strconv.Unquote(s[:end+1])
	if err != nil {
		return "", "", err
	}
	return name, s[end+1:], nil
}
