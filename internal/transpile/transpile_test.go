func transpile(t *testing.T, src string, in Input) (*Output, error) {
	t.Helper()
	toks, err := lex.Scan([]byte(src), lex.Options{IsRaw: func(n string, a []lex.Attr) bool {
		if n == tree.TagProp {
			for _, x := range a {
				if x.Name == "raw" {
					return true
				}
			}
		}
		return n == "Code"
	}})
	if err != nil {
		t.Fatalf("scan: %v", err)
	}
	f, err := tree.Build(toks)
	if err != nil {
		t.Fatalf("tree: %v", err)
	}
	in.File, in.Name, in.Hash = f, "p.html", "ab"
	if in.Line == 0 {
		in.Line = 1
	}
	return Transpile(in)
}

// stubFuncs lets html/template parse generated source.
var stubFuncs = template.FuncMap{
	FnRender: func(...any) string { return "" }, FnList: func(a ...any) []any { return a },
	FnOnce: func(v any) []any { return []any{v} }, FnCat: func(...any) string { return "" },
	FnWrap: func(a, b any) any { return b }, "__children": func(any) string { return "" },
	"__t": func(...any) string { return "" }, "__call_helpers_slugify": func(...any) string { return "" },
	"__call__price": func(...any) string { return "" },
}

// The generated source must always parse as a Go template.
func TestGeneratedSourceParses(t *testing.T) {
	t.Parallel()
	src := `<h1>{{ .Title }}</h1>{{ range $i, $p := .Posts }}<Card :n="$i" title="Hi {{ $p.T }}">{{ $p.Body }} {{ children }}<brick:prop name="h"><b>{{ $i }}</b></brick:prop></Card>{{ end }}` +
		`<Tabs><Tab title="a"/>{{ if .X }}<Tab :t=".Y"/>{{ end }}</Tabs>{{ define "row" }}{{ . }}{{ t "k" }}{{ end }}{{ template "row" .A }}{{ helpers.slugify .T }}{{ price 5 }}`
	out, err := transpile(t, src, Input{Namespaces: map[string]bool{"helpers": true}, ScriptFuncs: map[string]bool{"price": true}})
	if err != nil {
		t.Fatal(err)
	}
	if _, err := template.New("p.html").Funcs(stubFuncs).Parse(out.Source); err != nil {
		t.Fatalf("parse: %v\n%s", err, out.Source)
	}
	for _, want := range []string{
		`{{ __render $ 0 . (__list $i $p) (__list ($i) (__cat "Hi " ($p.T))) (__list) }}`,
		`{{ $p := index .Vars "p" }}{{ $ := .Root }}{{ range __once .Dot }}{{ $p.Body }} {{ __children $ }}{{ end }}`,
		`{{ template "row" (__wrap $ (.A)) }}`,
		`{{ define "row" }}{{ $ := .Root }}{{ range __once .Dot }}{{ . }}{{ __t $ "k" }}{{ end }}{{ end }}`,
		`{{ __call_helpers_slugify $ .T }}`,
		`{{ __call__price $ 5 }}`,
	} {
		if !strings.Contains(out.Source, want) {
			t.Fatalf("missing %s in\n%s", want, out.Source)
		}
	}
	tabs := out.Calls[1]
	if len(tabs.Kids) != 2 || len(out.Warnings) != 1 || !strings.Contains(out.Warnings[0].Msg, "inside {{ if }}") {
		t.Fatalf("kids=%d warnings=%v", len(tabs.Kids), out.Warnings)
	}
}

// Author bytes outside actions are copied exactly (S10).
func TestAuthorBytesVerbatim(t *testing.T) {
	t.Parallel()
	src := "<p class=\"x\">\n  a {{- .A -}}  b\r\n</p><!-- c -->"
	out, err := transpile(t, src, Input{})
	if err != nil {
		t.Fatal(err)
	}
	if out.Source != src {
		t.Fatalf("got %q", out.Source)
	}
}

// Every generated byte maps back to an author position (T10).
func TestSourceMap(t *testing.T) {
	t.Parallel()
	out, err := transpile(t, "a\nb <Card>\n  x {{ .Y }}\n</Card>", Input{Line: 5})
	if err != nil {
		t.Fatal(err)
	}
	covered := 0
	for i, s := range out.Segments {
		if i > 0 && s.Gen < out.Segments[i-1].Gen+out.Segments[i-1].Len {
			t.Fatalf("segments overlap or are unsorted: %+v", out.Segments)
		}
		covered += s.Len
	}
	if covered != len(out.Source)-strings.Count(out.Source, `{{ define "__brick_ab_1" }}`)*len(`{{ define "__brick_ab_1" }}`)-len("{{ end }}") {
		t.Fatalf("covered %d of %d bytes:\n%s", covered, len(out.Source), out.Source)
	}
	idx := strings.Index(out.Source, "{{ .Y }}")
	for _, s := range out.Segments {
		if idx >= s.Gen && idx < s.Gen+s.Len {
			if s.Src.Line != 7 || !s.Verbatim {
				t.Fatalf("{{ .Y }} maps to %+v, want line 7", s)
			}
			return
		}
	}
	t.Fatal("{{ .Y }} not mapped")
}

func TestTranspileErrors(t *testing.T) {
	t.Parallel()
	for _, tc := range []struct{ src, msg string }{
		{`{{ __render }}`, "reserved for the engine"},
		{`<Card :x="__y" />`, "reserved for the engine"},
		{`{{ define "__x" }}{{ end }}`, "reserved"},
		{`<Card title="{{ if .A }}x{{ end }}" />`, "{{ }} block cannot go inside an attribute"},
		{`<Card :x="$y := 1" />`, "cannot be declared inside an attribute"},
		{`<Card :x="" />`, "empty expression"},
		{`<Card title="a" :title=".B" />`, "given twice"},
		{`<Card title="a"><brick:prop name="title">x</brick:prop></Card>`, "given twice"},
		{`<brick:component name="lower">x</brick:component>`, "uppercase"},
		{`<brick:component name="P">x</brick:component><brick:component name="P">y</brick:component>`, "defined twice"},
	} {
		_, err := transpile(t, tc.src, Input{})
		var te *Error
		if !errors.As(err, &te) || !strings.Contains(te.Msg, tc.msg) {
			t.Fatalf("%s: err = %v, want %q", tc.src, err, tc.msg)
		}
	}
}

// Children that use variables declared inside the parent's body cannot be
// rendered alone, so they are left out of .Children with a warning (C7).
func TestKidsExcluded(t *testing.T) {
	t.Parallel()
	out, err := transpile(t, `<Tabs>{{ $x := 1 }}<Tab :v="$x"/>{{ range .L }}<Tab/>{{ end }}{{ with .W }}<Tab/>{{ end }}<Tab/></Tabs>`, Input{})
	if err != nil {
		t.Fatal(err)
	}
	if n := len(out.Calls[0].Kids); n != 1 {
		t.Fatalf("kids = %d, want 1", n)
	}
	if len(out.Warnings) != 1 || !strings.Contains(out.Warnings[0].Msg, "variable declared inside") {
		t.Fatalf("warnings = %v", out.Warnings)
	}
}

func TestRawAndPresence(t *testing.T) {
	t.Parallel()
	out, err := transpile(t, "<Code>a < b {{ x }}</Code><Card>  \n </Card><Card>{{/* c */}}</Card><Card> x </Card><Card><brick:prop name=\"q\" raw>\"quoted\" <b></brick:prop></Card>", Input{})
	if err != nil {
		t.Fatal(err)
	}
	c := out.Calls
	if !c[0].HasRaw || c[0].Raw != "a < b {{ x }}" || c[0].Body != "" {
		t.Fatalf("raw: %+v", c[0])
	}
	if c[1].HasChildren || c[2].HasChildren || !c[3].HasChildren {
		t.Fatalf("presence: %v %v %v", c[1].HasChildren, c[2].HasChildren, c[3].HasChildren)
	}
	if len(c[4].RawProps) != 1 || c[4].RawProps[0].Text != `"quoted" <b>` {
		t.Fatalf("raw prop: %+v", c[4].RawProps)
	}
}

// A valueless `:name` passes the variable $name (v22), and every way it
// could mean something else is a compile error, never a guess.
func TestPropShorthand(t *testing.T) {
	t.Parallel()
	out, err := transpile(t, `{{ range $post := .Posts }}<Card :post />{{ end }}`, Input{})
	if err != nil {
		t.Fatal(err)
	}
	c := out.Calls[0]
	if len(c.Props) != 1 || c.Props[0].Name != "post" || c.Props[0].Kind != Expr || c.dyn[0] != "($post)" {
		t.Fatalf("props = %+v dyn = %v", c.Props, c.dyn)
	}
	// Inside another component's body the variable still reaches the call.
	out, err = transpile(t, `{{ $user := .U }}<Box><Card :user /></Box>`, Input{})
	if err != nil {
		t.Fatal(err)
	}
	if !slices.Contains(out.Calls[0].Vars, "user") {
		t.Fatalf("outer call vars = %v, want user", out.Calls[0].Vars)
	}
	for _, tc := range []struct{ src, msg string }{
		{`<Card :post />`, "no $post is declared here"},
		{`{{ $x := 1 }}<Card :user-id />`, "is not a variable name"},
		{`{{ $a := 1 }}<Card :a.b />`, "is not a variable name"},
		{`{{ $post := 1 }}<Card :post :post="$post" />`, "given twice"},
		{`{{ $post := 1 }}<Card post="x" :post />`, "given twice"},
	} {
		_, err := transpile(t, tc.src, Input{})
		var te *Error
		if !errors.As(err, &te) || !strings.Contains(te.Msg, tc.msg) {
			t.Fatalf("%s: err = %v, want %q", tc.src, err, tc.msg)
		}
	}
}
