#!/usr/bin/env python3
"""Writes the component catalog in kit/README.md, between the
<!-- catalog:start --> and <!-- catalog:end --> markers, from the
frontmatter (title, category, description) of every doc page in
examples/ui/content/components/. Categories follow examples/ui/data/nav.yaml;
pages sort by title, case-insensitively.

  python3 scripts/kit_catalog.py           rewrite the catalog
  python3 scripts/kit_catalog.py --check   exit 1 when it is out of date

kit_catalog_test.go builds the same text in Go, so the gate needs no
Python; keep the two in step (the test fails when they disagree with the
README).
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
README = os.path.join(ROOT, "kit", "README.md")
PAGES = os.path.join(ROOT, "examples", "ui", "content", "components")
NAV = os.path.join(ROOT, "examples", "ui", "data", "nav.yaml")
START, END = "<!-- catalog:start -->", "<!-- catalog:end -->"
LINK = "../examples/ui/content/components/"


def scalar(v):
    """A one-line YAML scalar: plain, "double" (with \\" and \\\\) or 'single'."""
    v = v.strip()
    if len(v) >= 2 and v[0] == '"' and v[-1] == '"':
        return v[1:-1].replace('\\"', '"').replace("\\\\", "\\")
    if len(v) >= 2 and v[0] == "'" and v[-1] == "'":
        return v[1:-1].replace("''", "'")
    return v


def frontmatter(text):
    if not text.startswith("---\n"):
        return {}
    end = text.find("\n---", 4)
    if end < 0:
        return {}
    out = {}
    for line in text[4:end].split("\n"):
        m = re.match(r"^(title|category|description):(.*)$", line)
        if m:
            out[m.group(1)] = scalar(m.group(2))
    return out


def categories():
    out, inside = [], False
    with open(NAV, encoding="utf-8") as f:
        for line in f.read().split("\n"):
            if line.startswith("categories:"):
                inside = True
                continue
            if inside and line.startswith("  - "):
                out.append(scalar(line[4:]))
            elif inside and line and not line.startswith(" "):
                inside = False
    return out


def cell(s):
    return s.replace("|", "\\|")


def catalog():
    pages = {}
    for name in sorted(os.listdir(PAGES)):
        if not name.endswith(".html"):
            continue
        with open(os.path.join(PAGES, name), encoding="utf-8") as f:
            fm = frontmatter(f.read())
        if "title" in fm and "category" in fm:
            pages.setdefault(fm["category"], []).append((fm["title"], name, fm.get("description", "")))
    order = categories()
    order += sorted(c for c in pages if c not in order)
    lines = [START, "", "<!-- Generated by scripts/kit_catalog.py from the doc pages' frontmatter; do not edit by hand. -->"]
    for c in order:
        if c not in pages:
            continue
        lines += ["", "### " + c, "", "| Component | Description |", "|---|---|"]
        for title, name, desc in sorted(pages[c], key=lambda p: (p[0].lower(), p[1])):
            lines.append("| [" + cell(title) + "](" + LINK + name + ") | " + cell(desc) + " |")
    lines += ["", END]
    return "\n".join(lines)


def main():
    with open(README, encoding="utf-8") as f:
        text = f.read()
    a, b = text.find(START), text.find(END)
    if a < 0 or b < a:
        sys.exit("kit/README.md has no " + START + " … " + END + " markers")
    want = text[:a] + catalog() + text[b + len(END):]
    if "--check" in sys.argv[1:]:
        if want != text:
            sys.exit("kit/README.md: the component catalog is out of date; run python3 scripts/kit_catalog.py")
        return
    if want != text:
        with open(README, "w", encoding="utf-8") as f:
            f.write(want)


if __name__ == "__main__":
    main()
